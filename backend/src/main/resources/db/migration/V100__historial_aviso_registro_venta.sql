-- Los avisos a finanzas antes solo quedaban en el registro técnico del servidor.
CREATE TABLE historial_aviso_registro_venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL REFERENCES venta(id) ON DELETE CASCADE,
    fecha TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL,
    detalle VARCHAR(500)
);
CREATE INDEX idx_historial_aviso_registro_fecha ON historial_aviso_registro_venta (fecha);
